# 手册：升引擎版本 + 插入 3.14 节（纯 LF 文件，用 LF）
P = r"D:\game\elite-redux\docs\manual\功能清单与使用手册.md"
d = open(P, "rb").read()

# 1) 引擎版本
ver_old = "> 引擎版本 **v4.375**｜"
ver_new = "> 引擎版本 **v4.376**｜"
assert d.count(ver_old.encode("utf-8")) == 1
d = d.replace(ver_old.encode("utf-8"), ver_new.encode("utf-8"), 1)

# 2) 在 3.13 图片后的分隔线前插入 3.14
anchor = "![喷火龙答案卡：巨翼特性按招族判定](../shots/v4375_mvflag.png)\n\n---\n"
assert d.count(anchor.encode("utf-8")) == 1

sec = """### 3.14 防守流派死特性自动换常驻防守特性（v4.376）

**受队、联防、辅助流里，特性要是触发不了，等于白占一个槽。** 比如一只肉盾的首推是「叶绿素」（要晴天才加速），可这套配招里既没有晴天也没有晴队友，这个特性就永远不生效。旧版会老实标注「当前不生效」，但要你自己去备选里翻一个能用的。

**现在工具直接帮你换好。** 只要是防守流派（肉盾/受队/联防/辅助），首推特性确实拿不到触发条件，而备选里有「不依赖天气、场地、指定招式，常驻就生效」的防守特性——比如纯朴（无视对手强化）、硬壳盔甲（防暴击+减伤）、坚硬岩石（弱招减伤）、防尘、我行我素等，就自动把首推换成它，并写明原来的特性为什么不生效。

**换不掉的也不硬凑。** 如果备选里没有任何常驻防守特性，工具保留原来的诚实标注，不会随便塞一个同样没用的特性；进攻流派不在这个处理范围内。本版共 9 个防守流派（7 只宝可梦）换成了常驻防守特性，其余全库推荐不变。

![小锻匠R 钉子减伤轴：死特性自动换成硬壳盔甲](../shots/v4376_dead_swap.png)

"""
d = d.replace(anchor.encode("utf-8"),
              anchor.replace("\n\n---\n", "\n").encode("utf-8") + sec.encode("utf-8") + b"---\n", 1)
open(P, "wb").write(d)
print("done. CRLF:", d.count(b"\r\n"), "bareLF:", d.count(b"\n") - d.count(b"\r\n"))
